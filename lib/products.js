/** Derived fields are computed once so no screen has to recompute them. */
export const products = CATALOG.map((product) => {
  const image = img(product.photo);
  return {
    ...product,
    slug: product.id,
    image,
    images: [image, img(product.photo, 1400)],
    weight: product.unit,
    categoryLabel: CATEGORY_LABELS[product.category] ?? product.category,
    discountPercent: discountPercent(product.price, product.originalPrice),
    onSale: Boolean(product.originalPrice && product.originalPrice > product.price),
    deliveryTime: product.isFresh ? "Same day, 2 hours" : "Next day",
    vendor: { id: `vendor-${product.id}`, ...product.vendor },
  };
});

export const getProductById = (id) => products.find((product) => product.id === id) ?? null;

export const getProductBySlug = (slug) => products.find((product) => product.slug === slug) ?? null;

export const getProductsByCategory = (category) =>
  products.filter((product) => product.category === category);

export const getRelatedProducts = (product, limit = 5) =>
  products
    .filter((entry) => entry.id !== product?.id && entry.category === product?.category)
    .concat(products.filter((entry) => entry.id !== product?.id && entry.category !== product?.category))
    .slice(0, limit);

export const getBestsellers = (limit = 8) =>
  products.filter((product) => product.bestseller).slice(0, limit);

export const getDeals = (limit = 8) =>
  [...products]
    .filter((product) => product.discountPercent > 0)
    .sort((a, b) => b.discountPercent - a.discountPercent)
    .slice(0, limit);

export const getNewArrivals = (limit = 8) =>
  products.filter((product) => product.isNew).slice(0, limit);

export function searchProducts(query, limit = 8) {
  const term = query?.trim().toLowerCase();
  if (!term) return [];

  return products
    .map((product) => {
      const name = product.name.toLowerCase();
      // Prefix matches rank above substring matches, which rank above tags.
      const score = name.startsWith(term)
        ? 3
        : name.includes(term)
          ? 2
          : product.brand?.toLowerCase().includes(term) ||
              product.categoryLabel.toLowerCase().includes(term) ||
              product.tags?.some((tag) => tag.includes(term))
            ? 1
            : 0;
      return { product, score };
    })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score || b.product.rating - a.product.rating)
    .slice(0, limit)
    .map((entry) => entry.product);
}
