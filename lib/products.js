/** Small edit distance tolerance so "tomatoe", "garri" vs "gari" and typos still match. */
function nearlyEqual(a, b) {
  if (Math.abs(a.length - b.length) > 1 || a.length < 4) return false;
  let edits = 0;
  for (let i = 0, j = 0; i < a.length || j < b.length; i += 1, j += 1) {
    if (a[i] === b[j]) continue;
    edits += 1;
    if (edits > 1) return false;
    if (a.length > b.length) j -= 1;
    else if (b.length > a.length) i -= 1;
  }
  return true;
}

/** Relevance of one product to a search term. 0 means no match. */
export function scoreProduct(product, term) {
  const name = product.name.toLowerCase();
  if (name.startsWith(term)) return 5;
  if (product.aliases?.some((alias) => alias === term)) return 4.5;
  if (name.includes(term)) return 4;
  if (product.aliases?.some((alias) => alias.startsWith(term) || alias.includes(term))) return 3;
  if (
    product.brand?.toLowerCase().includes(term) ||
    product.categoryLabel.toLowerCase().includes(term) ||
    product.tags?.some((tag) => tag.includes(term))
  )
    return 2;
  const words = [...name.split(/[^a-z]+/), ...(product.aliases ?? [])];
  if (words.some((word) => nearlyEqual(word, term))) return 1;
  return 0;
}

export function searchProducts(query, limit = 8) {
  const term = query?.trim().toLowerCase();
  if (!term) return [];

  return products
    .map((product) => ({ product, score: scoreProduct(product, term) }))
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score || b.product.soldLastWeek - a.product.soldLastWeek)
    .slice(0, limit)
    .map((entry) => entry.product);
}
