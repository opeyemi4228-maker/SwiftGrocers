export const getRelatedProducts = (product, limit = 5) => {
  if (!product) return [];
  const paired = (PAIRINGS[product.id] ?? []).map(getProductById).filter(Boolean);
  const sameAisle = products.filter(
    (entry) => entry.id !== product.id && entry.category === product.category
  );
  const rest = products.filter((entry) => entry.id !== product.id && entry.bestseller);
  const seen = new Set();
  return [...paired, ...sameAisle, ...rest]
    .filter((entry) => (seen.has(entry.id) ? false : seen.add(entry.id)))
    .slice(0, limit);
};

