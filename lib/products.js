/** "₦1,840/kg", lets shoppers compare a 10 kg bag with a 50 kg one honestly. */
function unitPriceLabel(product) {
  const measure = product.measure;
  if (!measure || !measure.amount) return null;
  const per = product.price / measure.amount;
  return `${formatPrice(Math.round(per))}/${measure.unit}`;
}

