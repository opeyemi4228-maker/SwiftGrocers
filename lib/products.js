/**
 * Local names worth showing a person: aliases that aren't just the product
 * name again or a spelling of it ("tomatos"), which exist only for search.
 */
export function localNamesFor(product, limit = 4) {
  const stems = product.name.toLowerCase().split(/[^a-z]+/).filter((word) => word.length >= 3).map((word) => word.slice(0, 3));
  return (product.aliases ?? [])
    .filter((alias) => !alias.split(" ").some((word) => stems.includes(word.slice(0, 3))))
    .slice(0, limit);
}

